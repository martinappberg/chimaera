//! Shell integration: scripts that make interactive shells emit OSC 133
//! semantic prompts, OSC 633;E command-line reports, and OSC 7 cwd reports.
//!
//! Locally, [`shell_launch`] materializes the scripts under the runtime dir
//! and returns the argv + env that spawn the user's shell with the
//! integration injected (bash `--init-file`, zsh `ZDOTDIR` shim, fish
//! `vendor_conf.d`) while still sourcing their normal rc files. For remote
//! hosts (where nothing is installed), [`snippet`] returns a self-contained
//! bash+zsh script the user can append to a remote rc file.
//!
//! A zsh or bash terminal is a **login** shell, as in Terminal.app, iTerm and
//! tmux: the daemon's own environment is often one no profile ever ran in
//! (launchd under the native app, `chimaera serve` over ssh, a batch job),
//! so the profile (`.zprofile`, `.bash_profile`) has to run in the terminal
//! or what it sets is missing there. zsh takes `-l`; bash drops `--init-file`
//! under `--login`, so its init file reads the login files itself
//! (`BASH_INIT`). The startup order, both shells: profile, rc, integration,
//! shim dir back in front of PATH, environment prelude.

use std::path::{Path, PathBuf};

use anyhow::Context;

pub const BASH: &str = include_str!("shellint/integration.bash");
pub const ZSH: &str = include_str!("shellint/integration.zsh");
pub const FISH: &str = include_str!("shellint/integration.fish");

/// The environment-prelude sourcing block, POSIX syntax (bash and zsh both
/// source it verbatim; fish gets an env-capture handler in its integration
/// instead). Appended after the user's own rc so the prelude can override
/// it; also embedded in the server's agent login-wrapper — one source of
/// truth for the guard semantics. The DONE guard stops nested integrated
/// shells from re-running the prelude; `[ -r ]` makes a missing file a
/// no-op rather than a startup error.
pub const PRELUDE_SNIPPET_POSIX: &str = "\
# Chimaera environment prelude: user-configured startup commands, run once\n\
# per session (the DONE guard covers nested shells; reconnect never re-runs\n\
# it because reattach is not a spawn).\n\
if [ -n \"${CHIMAERA_PRELUDE:-}\" ] && [ -z \"${CHIMAERA_PRELUDE_DONE:-}\" ] && [ -r \"$CHIMAERA_PRELUDE\" ]; then\n\
  export CHIMAERA_PRELUDE_DONE=1\n\
  . \"$CHIMAERA_PRELUDE\"\n\
fi\n";

/// Puts the session's shim dir (`CHIMAERA_SHIMS`, set by the daemon's spawn
/// env) back in front of PATH after the startup files, listed once: a login
/// profile reorders the PATH the spawn started with (macOS `path_helper`
/// moves the system directories to the front, which left the shim dir last),
/// and an rc may prepend its own. Nothing else in PATH moves. The loop is
/// for adjacent copies, which one substitution pass leaves behind. A PATH
/// that ends up empty yields the dir alone, never a trailing `:` (an empty
/// member is the cwd). bash 3.2 and zsh both run it verbatim.
const SHIMS_SNIPPET_POSIX: &str = r#"# The shim dir leads PATH again after the startup files reordered it.
if [ -n "${CHIMAERA_SHIMS:-}" ]; then
  __chimaera_path=":$PATH:"
  while :; do
    case "$__chimaera_path" in
      *":$CHIMAERA_SHIMS:"*) __chimaera_path=${__chimaera_path//":$CHIMAERA_SHIMS:"/:} ;;
      *) break ;;
    esac
  done
  __chimaera_path=${__chimaera_path#:}
  __chimaera_path=${__chimaera_path%:}
  PATH="$CHIMAERA_SHIMS${__chimaera_path:+:$__chimaera_path}"
  export PATH
  unset __chimaera_path
fi
"#;

/// The `--init-file` of a bash terminal, `@INTEGRATION@` standing for the
/// integration script's path. bash reads no init file under `--login`, so
/// this file is the login startup: `/etc/profile`, then the first readable
/// of the three profiles, the files and order of a login bash. What it
/// cannot give: `shopt login_shell` stays off, `~/.bash_logout` is not run,
/// and bash has already read its system rc where it is built with one
/// (Debian's `/etc/bash.bashrc`), which `/etc/profile` then reads again.
///
/// `~/.bashrc` is then read unless that profile already sourced it, so it
/// runs once. Whether it did is read off the profile's text: a `.` or
/// `source` of a path ending in `/.bashrc`, outside a comment and outside a
/// quoted string, in the profile itself or in the `~/.profile` it sources.
/// Mentions that source nothing (an alias, a comment, an `echo` of a tip,
/// `/etc/bashrc`, `~/.bashrc.d`) don't count, because the two wrong guesses
/// are not equal: an rc read twice is what a shell opened inside a login
/// session does, an rc never read is a terminal without its aliases. Text
/// cannot tell a `source` on a branch the profile does not take.
///
/// The profile is sourced outside the loop that finds it, so a stray
/// `break` in one cannot end up steering this file.
const BASH_INIT: &str = r##"# Generated by chimaera: the --init-file for integrated bash sessions.
# bash reads no --init-file under --login, so this file reads what a login
# bash reads, in its order, then ~/.bashrc unless the profile sourced it.
if [ -r /etc/profile ]; then . /etc/profile; fi
__chimaera_sources() {
  command grep -Eq "^(([^#\"']|\"[^\"]*\"|'[^']*')*[;&|[:space:]])?(\\.|source)[[:space:]]+([^[:space:]]*/)?\\.$1([^[:alnum:]_.-]|\$)" "$2" 2>/dev/null
}
__chimaera_profile=
for __chimaera_p in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
  if [ -r "$__chimaera_p" ]; then __chimaera_profile=$__chimaera_p; break; fi
done
__chimaera_rc=1
if [ -n "$__chimaera_profile" ]; then
  if __chimaera_sources bashrc "$__chimaera_profile"; then
    __chimaera_rc=
  elif [ "$__chimaera_profile" != "$HOME/.profile" ] && __chimaera_sources profile "$__chimaera_profile" && __chimaera_sources bashrc "$HOME/.profile"; then
    __chimaera_rc=
  fi
fi
unset -f __chimaera_sources
unset __chimaera_p
if [ -n "$__chimaera_profile" ]; then . "$__chimaera_profile"; fi
if [ -n "$__chimaera_rc" ] && [ -r "$HOME/.bashrc" ]; then . "$HOME/.bashrc"; fi
unset __chimaera_profile __chimaera_rc
. "@INTEGRATION@"
"##;

/// How to spawn a shell with integration injected.
#[derive(Clone, Debug)]
pub struct ShellLaunch {
    pub argv: Vec<String>,
    pub env: Vec<(String, String)>,
}

/// The self-contained bash+zsh snippet for remote hosts.
pub fn snippet() -> String {
    format!(
        "# Chimaera shell integration (bash + zsh) — makes this shell report\n\
         # command boundaries, exit codes, and cwd to a chimaera terminal, so\n\
         # linked agents get a reliable command journal on this host too.\n\
         #\n\
         # Install on a remote host:\n\
         #   chimaera shell-integration | ssh HOST 'cat >> ~/.bashrc'   # bash\n\
         #   chimaera shell-integration | ssh HOST 'cat >> ~/.zshrc'    # zsh\n\
         if [ -n \"${{ZSH_VERSION:-}}\" ]; then\n{ZSH}\nelif [ -n \"${{BASH_VERSION:-}}\" ]; then\n{BASH}\nfi\n"
    )
}

/// Write `content` to `path` unless it already matches (keeps mtimes stable
/// and sourcing shells never see a half-written file thanks to the rename).
fn write_if_changed(path: &Path, content: &str) -> anyhow::Result<()> {
    if std::fs::read_to_string(path).is_ok_and(|cur| cur == content) {
        return Ok(());
    }
    let tmp = path.with_extension("tmp");
    std::fs::write(&tmp, content).with_context(|| format!("write {}", tmp.display()))?;
    std::fs::rename(&tmp, path).with_context(|| format!("rename to {}", path.display()))?;
    Ok(())
}

/// A zsh ZDOTDIR-shim dotfile: source the user's counterpart (restoring
/// their ZDOTDIR while it runs, VS Code-style), then optionally the
/// integration.
fn zsh_shim(dotfile: &str, integration: Option<&Path>) -> String {
    let mut s = format!(
        "__chimaera_zdot=\"${{CHIMAERA_ORIG_ZDOTDIR:-$HOME}}\"\n\
         if [ -f \"$__chimaera_zdot/{dotfile}\" ]; then\n\
         \t__chimaera_own_zdotdir=\"$ZDOTDIR\"\n\
         \tZDOTDIR=\"$__chimaera_zdot\"\n\
         \t. \"$__chimaera_zdot/{dotfile}\"\n\
         \t# Respect an rc that intentionally re-homes ZDOTDIR; otherwise\n\
         \t# keep ours so the remaining startup files stay shimmed.\n\
         \tif [ \"$ZDOTDIR\" = \"$__chimaera_zdot\" ]; then\n\
         \t\tZDOTDIR=\"$__chimaera_own_zdotdir\"\n\
         \tfi\n\
         \tunset __chimaera_own_zdotdir\n\
         fi\n\
         unset __chimaera_zdot\n"
    );
    if let Some(integration) = integration {
        s.push_str(&format!(". \"{}\"\n", integration.display()));
    }
    s
}

/// Materialize the integration files under `base` (normally the runtime
/// dir); idempotent. Returns the shell-integration directory.
pub fn materialize_in(base: &Path) -> anyhow::Result<PathBuf> {
    let dir = base.join("shell-integration");
    let zsh_dir = dir.join("zsh");
    let fish_dir = dir.join("fish-xdg").join("fish").join("vendor_conf.d");
    std::fs::create_dir_all(&zsh_dir).with_context(|| format!("mkdir {}", zsh_dir.display()))?;
    std::fs::create_dir_all(&fish_dir).with_context(|| format!("mkdir {}", fish_dir.display()))?;

    let bash_script = dir.join("integration.bash");
    let zsh_script = dir.join("integration.zsh");
    write_if_changed(&bash_script, BASH)?;
    write_if_changed(&zsh_script, ZSH)?;
    write_if_changed(&fish_dir.join("chimaera.fish"), FISH)?;

    // Both shells end their startup the same way: the shim dir back in front
    // of PATH, then the environment prelude (last, so it can override the
    // startup files).
    let tail = format!("{SHIMS_SNIPPET_POSIX}{PRELUDE_SNIPPET_POSIX}");

    write_if_changed(
        &dir.join("bash-init.sh"),
        &format!(
            "{}{tail}",
            BASH_INIT.replace("@INTEGRATION@", &bash_script.to_string_lossy())
        ),
    )?;

    for dotfile in [".zshenv", ".zprofile", ".zlogout"] {
        write_if_changed(&zsh_dir.join(dotfile), &zsh_shim(dotfile, None))?;
    }
    // The tail belongs after the last startup file. In a login shell that is
    // .zlogin, which zsh reads after .zshrc; the .zshrc shim runs it only
    // when no .zlogin shim will: a shell that is not login (a `zsh` typed in
    // the terminal), or an rc that re-homed ZDOTDIR. Never from
    // .zshenv/.zprofile: those also run before the interactive rc. (A file
    // that `exec`s a new zsh while it is being sourced is out of reach, as
    // before: ZDOTDIR is the user's own for that moment, so the new shell
    // never sees the shim.)
    write_if_changed(
        &zsh_dir.join(".zshrc"),
        &format!(
            "{}if [[ ! -o login || \"$ZDOTDIR\" != \"{}\" ]]; then\n{tail}fi\n",
            zsh_shim(".zshrc", Some(&zsh_script)),
            zsh_dir.display()
        ),
    )?;
    write_if_changed(
        &zsh_dir.join(".zlogin"),
        &format!("{}{tail}", zsh_shim(".zlogin", None)),
    )?;

    Ok(dir)
}

/// Compose the launch for `shell` with integration injected, materializing
/// scripts under `base`. Unknown shells launch plain (no integration).
pub fn shell_launch_for(shell: &str, base: &Path) -> anyhow::Result<ShellLaunch> {
    let dir = materialize_in(base)?;
    let name = Path::new(shell)
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let mut launch = ShellLaunch {
        argv: vec![shell.to_string()],
        env: Vec::new(),
    };
    match name.as_str() {
        "bash" => {
            // Not `--login`: bash would then ignore the init file, which
            // reads the login files itself (`BASH_INIT`).
            launch.argv.push("--init-file".to_string());
            launch
                .argv
                .push(dir.join("bash-init.sh").to_string_lossy().into_owned());
        }
        "zsh" => {
            launch.argv.push("-l".to_string());
            if let Some(orig) = std::env::var_os("ZDOTDIR") {
                launch.env.push((
                    "CHIMAERA_ORIG_ZDOTDIR".to_string(),
                    orig.to_string_lossy().into_owned(),
                ));
            }
            launch.env.push((
                "ZDOTDIR".to_string(),
                dir.join("zsh").to_string_lossy().into_owned(),
            ));
        }
        // fish stays as it was, not login: it has no profile file (every
        // fish reads `config.fish`), so only `status is-login` blocks and its
        // own macOS `/etc/paths` import are left out.
        "fish" => {
            let ours = dir.join("fish-xdg").to_string_lossy().into_owned();
            let value = match std::env::var("XDG_DATA_DIRS") {
                Ok(cur) if !cur.is_empty() => format!("{ours}:{cur}"),
                // fish falls back to its builtin defaults only when the var
                // is unset, so re-supply them alongside ours.
                _ => format!("{ours}:/usr/local/share:/usr/share"),
            };
            launch.env.push(("XDG_DATA_DIRS".to_string(), value));
        }
        _ => {}
    }
    Ok(launch)
}

/// [`shell_launch_for`] on the user's real login shell under the runtime dir.
/// Resolved via [`crate::login_shell`] (passwd-backed) rather than raw
/// `$SHELL`, so a daemon launched from Finder/launchd — where `$SHELL` is
/// often absent — still opens the user's actual shell, not a `/bin/sh`/bash
/// stand-in.
pub fn shell_launch() -> anyhow::Result<ShellLaunch> {
    shell_launch_for(&crate::login_shell(), &crate::runtime_dir())
}

