    #[test]
    fn prelude_hook_reaches_every_shell() {
        // bash + zsh source the POSIX snippet after the user's rc; fish
        // carries its own env-capture handler. All three must be guarded.
        let base = test_base("prelude");
        let dir = materialize_in(&base).unwrap();

        let bash_init = std::fs::read_to_string(dir.join("bash-init.sh")).unwrap();
        let zshrc = std::fs::read_to_string(dir.join("zsh/.zshrc")).unwrap();
        let zlogin = std::fs::read_to_string(dir.join("zsh/.zlogin")).unwrap();
        // The last thing a terminal's startup does: the shim dir back in
        // front of PATH, then the prelude. For a login zsh that is the end
        // of .zlogin, the last startup file it reads.
        let tail = format!("{SHIMS_SNIPPET_POSIX}{PRELUDE_SNIPPET_POSIX}");
        for (label, content) in [("bash-init.sh", &bash_init), ("zsh/.zlogin", &zlogin)] {
            assert!(
                content.ends_with(&tail),
                "{label} must end with the shim dir + prelude block"
            );
        }
        // .zshrc carries the same tail for a shell with no .zlogin shim to
        // come (not login, or ZDOTDIR re-homed), and only for that one.
        let guard = zshrc
            .find("if [[ ! -o login || \"$ZDOTDIR\" != ")
            .expect("the .zshrc tail is guarded");
        assert!(zshrc.ends_with(&format!("{tail}fi\n")), "{zshrc}");
        assert!(zshrc.find("integration.zsh").unwrap() < guard);
        assert!(guard < zshrc.find("CHIMAERA_PRELUDE").unwrap());
        // The user's own files source BEFORE the tail (order is the contract).
        let at = |hay: &str, needle: &str| hay.find(needle).unwrap_or_else(|| panic!("{needle}"));
        assert!(at(&bash_init, ". /etc/profile") < at(&bash_init, ". \"$__chimaera_profile\""));
        assert!(
            at(&bash_init, ". \"$__chimaera_profile\"") < at(&bash_init, ". \"$HOME/.bashrc\"")
        );
        assert!(at(&bash_init, ". \"$HOME/.bashrc\"") < at(&bash_init, "integration.bash"));
        assert!(at(&bash_init, "integration.bash") < at(&bash_init, "CHIMAERA_SHIMS"));
        assert!(at(&zshrc, ".zshrc") < at(&zshrc, "CHIMAERA_PRELUDE"));
        assert!(at(&zlogin, ".zlogin") < at(&zlogin, "CHIMAERA_PRELUDE"));
        // The other zsh files are forwarded, never given the tail.
        for other in [".zshenv", ".zprofile", ".zlogout"] {
            let content = std::fs::read_to_string(dir.join("zsh").join(other)).unwrap();
            assert!(content.contains(other), "{other} must forward");
            assert!(!content.contains("CHIMAERA_PRELUDE"), "{other}");
        }

        for probe in ["CHIMAERA_PRELUDE", "CHIMAERA_PRELUDE_DONE"] {
            assert!(PRELUDE_SNIPPET_POSIX.contains(probe));
            assert!(FISH.contains(probe), "fish handler missing {probe}");
        }
        // fish must defer past config.fish (conf.d loads first) and
        // self-erase so the prelude runs exactly once.
        assert!(FISH.contains("--on-event fish_prompt"));
        assert!(FISH.contains("functions -e __chimaera_prelude"));

        std::fs::remove_dir_all(&base).ok();
    }

    /// Drive a real interactive bash (`-i`, piped stdin — PROMPT_COMMAND and
    /// the DEBUG trap run without a pty) with `prelude` sourced before the
    /// integration and `epilogue` after (both simulate a user rc), typing
    /// `commands`. Returns combined stdout+stderr (marks land on both).
    #[cfg(unix)]
    fn bash_probe(label: &str, prelude: &str, epilogue: &str, commands: &str) -> String {
        use std::io::Write;
        use std::process::{Command, Stdio};

        let dir = test_base(label);
        std::fs::write(dir.join("integration.bash"), BASH).unwrap();
        let rc = dir.join("rc.sh");
        std::fs::write(
            &rc,
            format!(
                "{prelude}\n. \"{}\"\n{epilogue}\n",
                dir.join("integration.bash").display()
            ),
        )
        .unwrap();
        let mut child = Command::new("bash")
            .args(["--noprofile", "--init-file"])
            .arg(&rc)
            .arg("-i")
            .env_remove("PROMPT_COMMAND")
            .env_remove("CHIMAERA_INTEGRATION")
            .env_remove("BASH_ENV")
            .env("TERM", "xterm-256color")
            .env("HISTFILE", "")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("spawn bash");
        child
            .stdin
            .take()
            .unwrap()
            .write_all(commands.as_bytes())
            .unwrap();
        let out = child.wait_with_output().unwrap();
        std::fs::remove_dir_all(&dir).ok();
        format!(
            "{}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )
    }

    /// The command-start hook must be the DEBUG trap (works on every bash
    /// since 3.2, unlike PS0 which needs 4.4), installed at source time
    /// and re-armed from PROMPT_COMMAND — asserted against the running
    /// bash, whatever version the host has.
    #[test]
    #[cfg(unix)]
    fn bash_debug_hook_installed_and_rearmed() {
        let out = bash_probe(
            "hook",
            "",
            "",
            "trap -p DEBUG\nprintf 'PC=%s\\n' \"$PROMPT_COMMAND\"\n",
        );
        assert!(out.contains("__chimaera_preexec"), "hook missing: {out}");
        assert!(
            out.contains(r#"trap "$__chimaera_debug_chain" DEBUG"#),
            "re-arm missing from PROMPT_COMMAND: {out}"
        );
    }

    /// The login-node scenario on a production cluster: a site rc has already installed a
    /// DEBUG trap whose handler calls functions (user-audit shells). The
    /// integration must still emit command-start/done marks — on bash < 4.4
    /// that takes the prompt-time re-arm, because trap changes made while an
    /// rc is sourced get silently reverted there — and the site's handler
    /// must keep running (chained).
    #[test]
    #[cfg(unix)]
    fn bash_marks_survive_hostile_audit_trap() {
        let prelude = r#"
user_audit() { local CMD; CMD=$(HISTTIMEFORMAT='' builtin history 1); : "$CMD"; }
debug_trap() { local _orig=$1; user_audit; echo AUDIT-RAN; : "$_orig"; }
trap 'debug_trap "$_"' DEBUG
PROMPT_COMMAND='RET=$?; : logger-standin'
"#;
        let out = bash_probe("hostile", prelude, "", "echo mark-test\n");
        assert!(out.contains("\x1b]133;C"), "no command-start mark: {out}");
        assert!(out.contains("\x1b]133;D;0"), "no done mark: {out}");
        assert!(
            out.contains("\x1b]633;E;echo mark-test"),
            "no command report: {out}"
        );
        assert!(out.contains("AUDIT-RAN"), "prior trap not chained: {out}");
    }

    /// A prior PROMPT_COMMAND that re-traps DEBUG at every prompt (site rc
    /// machinery runs before the integration wraps around it): the per-
    /// prompt re-arm executes after it, so the hook must win on every bash
    /// — commands still carry a command-start mark directly before their
    /// output. Without the re-arm, the thief keeps the trap on bash >= 4.4.
    #[test]
    #[cfg(unix)]
    fn bash_rearm_beats_prompt_time_trap_thief() {
        let prelude = "PROMPT_COMMAND='trap : DEBUG'";
        let out = bash_probe("thief", prelude, "", "echo first\necho recovered\n");
        assert!(
            out.contains("\x1b]133;C\x07recovered"),
            "re-arm did not keep the hook: {out:?}"
        );
    }

    /// A scalar PROMPT_COMMAND ending in `;` (common in rc files: `history
    /// -a;`) or in a `# comment` must not break the chain: a `; ` separator
    /// made `;;` a syntax error at every prompt, or let the comment swallow
    /// the re-arm, so no command ever got its C/D marks.
    #[test]
    #[cfg(unix)]
    fn bash_scalar_prompt_command_with_trailing_semicolon_or_comment_keeps_marks() {
        for prelude in [
            r#"PROMPT_COMMAND='printf "PC-RAN\n";'"#,
            r#"PROMPT_COMMAND='printf "PC-RAN\n" # trailing comment'"#,
        ] {
            let out = bash_probe(
                "prompt-scalar-tail",
                prelude,
                "",
                "(exit 5)\nprintf '\\nCOMMAND_OUTPUT\\n'\n",
            );
            assert!(!out.contains("syntax error"), "{prelude}: {out:?}");
            assert!(out.contains("PC-RAN"), "{prelude}: {out:?}");
            assert!(out.contains("\x1b]133;D;5\x07"), "{prelude}: {out:?}");
            assert!(out.lines().any(|line| line == "COMMAND_OUTPUT"), "{out:?}");
        }
    }

    /// Modern distro rc files use indexed PROMPT_COMMAND arrays. A scalar
    /// replacement only changes index zero, so a later entry would consume the
    /// preexec arm while the prompt is still rendering. Preserve sparse entries
    /// in execution order and the status observed by their first handler.
    #[test]
    #[cfg(unix)]
    fn bash_prompt_command_array_keeps_order_status_and_final_arm() {
        let prelude = r#"
first_prompt() { local status=$?; printf 'FIRST:%s\n' "$status"; return "$status"; }
second_prompt() { printf 'SECOND\n'; }
PROMPT_COMMAND=([0]="first_prompt # keep this comment" [5]=second_prompt)
"#;
        let out = bash_probe(
            "prompt-array",
            prelude,
            "",
            r#"if [[ ${#PROMPT_COMMAND[@]} = 1 && $PROMPT_COMMAND = '__chimaera_precmd'*'first_prompt # keep this comment'*'second_prompt'*'trap "$__chimaera_debug_chain" DEBUG; __chimaera_arm' ]]; then printf '\nARRAY_LAYOUT_OK\n'; fi
(exit 7)
printf '\nCOMMAND_OUTPUT\n'
"#,
        );
        assert!(out.lines().any(|line| line == "ARRAY_LAYOUT_OK"), "{out:?}");
        assert!(out.contains("FIRST:7\nSECOND\n"), "{out:?}");
        assert!(out.contains("\x1b]133;D;7\x07"), "{out:?}");
        assert!(out.lines().any(|line| line == "COMMAND_OUTPUT"), "{out:?}");
    }

    /// What a startup run left behind, read back from one `RESULT:` line.
    #[cfg(unix)]
    #[derive(Debug)]
    struct Startup {
        /// The order the fixture startup files ran in, `>`-separated.
        order: String,
        path: Vec<String>,
        prelude_done: String,
        out: String,
    }

    /// Start `shell` the way a terminal starts it (`shell_launch_for`), on a
    /// throwaway HOME holding `files`, from an environment no profile ran in,
    /// and report what its startup files left. Each fixture file appends its
    /// name to `ORDER`; the prelude appends `prelude`. `None` when the shell
    /// is not installed (zsh on a CI image).
    #[cfg(unix)]
    fn startup_probe(label: &str, shell: &str, files: &[(&str, &str)]) -> Option<Startup> {
        use std::io::Write;
        use std::process::{Command, Stdio};

        if !Path::new(shell).is_file() {
            return None;
        }
        let base = test_base(label);
        let home = base.join("home");
        std::fs::create_dir_all(&home).unwrap();
        for (name, body) in files {
            std::fs::write(home.join(name), body).unwrap();
        }
        let prelude = base.join("prelude.sh");
        std::fs::write(&prelude, "export ORDER=\"${ORDER:-}>prelude\"\n").unwrap();
        let shims = base.join("shims");
        std::fs::create_dir_all(&shims).unwrap();

        let launch = shell_launch_for(shell, &base).unwrap();
        let mut child = Command::new(&launch.argv[0])
            .args(&launch.argv[1..])
            .arg("-i")
            .env_clear()
            .envs(launch.env.iter().map(|(k, v)| (k.as_str(), v.as_str())))
            .env("HOME", &home)
            .env("TERM", "xterm-256color")
            .env("HISTFILE", "")
            // What the daemon's spawn env sets: the shim dir leads PATH.
            .env(
                "PATH",
                format!("{}:/usr/bin:/bin:/usr/sbin:/sbin", shims.display()),
            )
            .env("CHIMAERA_SHIMS", &shims)
            .env("CHIMAERA_PRELUDE", &prelude)
            .current_dir(&base)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("spawn shell");
        child
            .stdin
            .take()
            .unwrap()
            .write_all(
                b"printf '\\nRESULT:%s|%s|%s\\n' \"$ORDER\" \"$PATH\" \"$CHIMAERA_PRELUDE_DONE\"\nexit\n",
            )
            .unwrap();
        let output = child.wait_with_output().unwrap();
        let out = format!(
            "{}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        let line = out
            .lines()
            .find_map(|l| l.strip_prefix("RESULT:"))
            .unwrap_or_else(|| panic!("no result line: {out}"));
        let mut parts = line.split('|');
        let order = parts.next().unwrap().to_string();
        let shims = shims.to_string_lossy().into_owned();
        let home = home.to_string_lossy().into_owned();
        let path = parts
            .next()
            .unwrap()
            .split(':')
            .map(|p| {
                if p == shims {
                    "SHIMS".to_string()
                } else {
                    p.replace(&home, "~")
                }
            })
            .collect();
        let prelude_done = parts.next().unwrap().to_string();
        std::fs::remove_dir_all(&base).ok();
        Some(Startup {
            order,
            path,
            prelude_done,
            out,
        })
    }

    /// A fixture startup file: records that it ran and prepends a PATH entry.
    #[cfg(unix)]
    fn mark(name: &str) -> String {
        format!("export ORDER=\"${{ORDER:-}}>{name}\"\nexport PATH=\"$HOME/{name}-bin:$PATH\"\n")
    }

    /// The shim dir leads PATH exactly once, and what the startup files
    /// prepended follows in the order they ran (latest first).
    #[cfg(unix)]
    fn assert_path(s: &Startup, prepended: &[&str]) {
        assert_eq!(s.path[0], "SHIMS", "{s:?}");
        assert_eq!(
            s.path.iter().filter(|p| *p == "SHIMS").count(),
            1,
            "shim dir listed twice: {s:?}"
        );
        let want: Vec<String> = prepended.iter().map(|n| format!("~/{n}-bin")).collect();
        assert_eq!(&s.path[1..=want.len()], &want[..], "{s:?}");
        assert!(s.path.iter().any(|p| p == "/usr/bin"), "{s:?}");
        assert!(s.path.iter().all(|p| !p.is_empty()), "empty member: {s:?}");
    }

    /// A bash terminal reads the profile a login bash reads, then `~/.bashrc`,
    /// then the prelude: a variable set only in `.bash_profile` used to be
    /// absent from the terminal.
    #[test]
    #[cfg(unix)]
    fn bash_terminal_reads_profile_then_rc_then_prelude() {
        let s = startup_probe(
            "bash-plain",
            "/bin/bash",
            &[
                (".bash_profile", &mark("profile")),
                (".bashrc", &mark("rc")),
            ],
        )
        .expect("bash");
        assert_eq!(s.order, ">profile>rc>prelude", "{s:?}");
        assert_eq!(s.prelude_done, "1", "{s:?}");
        assert_path(&s, &["rc", "profile"]);
    }

    /// The stock profiles source `~/.bashrc` themselves; it must run once,
    /// not again after the profile. Covered: the profile bash reads, and the
    /// `~/.profile` a `.bash_profile` hands over to.
    #[test]
    #[cfg(unix)]
    fn bash_terminal_reads_an_rc_the_profile_sources_once() {
        let stock = format!(
            "if [ -f ~/.bashrc ]; then\n\t. ~/.bashrc\nfi\n{}",
            mark("profile")
        );
        let s = startup_probe(
            "bash-stock",
            "/bin/bash",
            &[(".bash_profile", &stock), (".bashrc", &mark("rc"))],
        )
        .expect("bash");
        assert_eq!(s.order, ">rc>profile>prelude", "{s:?}");
        assert_path(&s, &["profile", "rc"]);

        let debian = format!(
            "if [ -n \"$BASH_VERSION\" ]; then\n    if [ -f \"$HOME/.bashrc\" ]; then\n\t. \"$HOME/.bashrc\"\n    fi\nfi\n{}",
            mark("dotprofile")
        );
        // Quoted paths and a `#` inside a string are still a real source.
        let hands_over = format!(
            "[ -r \"$HOME/.profile\" ] && echo \"#\" >/dev/null && source \"$HOME/.profile\"\n{}",
            mark("profile")
        );
        let s = startup_probe(
            "bash-chain",
            "/bin/bash",
            &[
                (".bash_profile", &hands_over),
                (".profile", &debian),
                (".bashrc", &mark("rc")),
            ],
        )
        .expect("bash");
        assert_eq!(s.order, ">rc>dotprofile>profile>prelude", "{s:?}");
    }

    /// bash reads the first readable profile only, and a profile that merely
    /// mentions `.bashrc` (a comment, an alias, another file of a similar
    /// name) has not sourced it: the terminal must still read it, as every
    /// terminal did before terminals read profiles.
    #[test]
    #[cfg(unix)]
    fn bash_terminal_keeps_the_rc_when_the_profile_only_mentions_it() {
        let mentions = format!(
            "# . ~/.bashrc is read later\nalias erc='vi ~/.bashrc'\necho \"tip: source ~/.bashrc\" >/dev/null\n[ -f /etc/bashrc.none ] && . /etc/bashrc.none\n[ -f ~/.bashrc.d/none ] && . ~/.bashrc.d/none\n{}",
            mark("login")
        );
        let s = startup_probe(
            "bash-mention",
            "/bin/bash",
            &[
                (".bash_login", &mentions),
                (".profile", &mark("dotprofile")),
                (".bashrc", &mark("rc")),
            ],
        )
        .expect("bash");
        assert_eq!(s.order, ">login>rc>prelude", "{s:?}");

        // No profile at all: the rc alone, as before. An rc that leaves the
        // shim dir in PATH several times over, adjacent copies included,
        // still ends with it listed once.
        let repeats = format!(
            "{}export PATH=\"$CHIMAERA_SHIMS:$CHIMAERA_SHIMS:$PATH:$CHIMAERA_SHIMS\"\n",
            mark("rc")
        );
        let s = startup_probe("bash-rc-only", "/bin/bash", &[(".bashrc", &repeats)]).expect("bash");
        assert_eq!(s.order, ">rc>prelude", "{s:?}");
        assert_path(&s, &["rc"]);
    }

    /// A zsh terminal is a login shell behind the ZDOTDIR shim: `.zprofile`,
    /// `.zshrc`, `.zlogin` in zsh's own order, the prelude after the last of
    /// them, and `.zlogout` when it ends.
    #[test]
    #[cfg(unix)]
    fn zsh_terminal_is_a_login_shell_with_the_prelude_last() {
        let Some(s) = startup_probe(
            "zsh-login",
            "/bin/zsh",
            &[
                (".zshenv", &mark("env")),
                (".zprofile", &mark("profile")),
                (".zshrc", &mark("rc")),
                (
                    ".zlogin",
                    &format!(
                        "{}export PATH=\"$PATH:$CHIMAERA_SHIMS:$CHIMAERA_SHIMS\"\n",
                        mark("login")
                    ),
                ),
                (".zlogout", "print LOGOUT-RAN\n"),
            ],
        ) else {
            return;
        };
        assert_eq!(s.order, ">env>profile>rc>login>prelude", "{s:?}");
        assert_eq!(s.prelude_done, "1", "{s:?}");
        assert_path(&s, &["login", "rc", "profile"]);
        assert!(s.out.contains("LOGOUT-RAN"), "{s:?}");
    }

    /// An rc that re-homes `ZDOTDIR` takes the rest of the startup away from
    /// the shim (zsh reads `.zlogin` from the new place), so the `.zshrc`
    /// shim must end the startup itself or the prelude would never run.
    #[test]
    #[cfg(unix)]
    fn zsh_rc_that_rehomes_zdotdir_still_gets_the_prelude() {
        let rehome = format!(
            "{}mkdir -p \"$HOME/zd\"\nZDOTDIR=\"$HOME/zd\"\n",
            mark("rc")
        );
        let Some(s) = startup_probe(
            "zsh-rehome",
            "/bin/zsh",
            &[(".zprofile", &mark("profile")), (".zshrc", &rehome)],
        ) else {
            return;
        };
        assert_eq!(s.order, ">profile>rc>prelude", "{s:?}");
        assert_path(&s, &["rc", "profile"]);
    }

    /// The `.zshrc` shim still ends a startup that no `.zlogin` shim will: a
    /// zsh that is not login (one typed in a terminal) runs the prelude
    /// there, once, and reads no profile.
    #[test]
    #[cfg(unix)]
    fn zsh_nonlogin_shell_runs_the_prelude_from_the_rc_shim() {
        use std::process::Command;

        if !Path::new("/bin/zsh").is_file() {
            return;
        }
        let base = test_base("zsh-nonlogin");
        let home = base.join("home");
        std::fs::create_dir_all(&home).unwrap();
        std::fs::write(home.join(".zshrc"), mark("rc")).unwrap();
        std::fs::write(home.join(".zprofile"), mark("profile")).unwrap();
        let prelude = base.join("prelude.sh");
        std::fs::write(&prelude, "export ORDER=\"${ORDER:-}>prelude\"\n").unwrap();
        let launch = shell_launch_for("/bin/zsh", &base).unwrap();
        let out = Command::new("/bin/zsh")
            .args(["-i", "-c", "print -r -- RESULT:$ORDER"])
            .env_clear()
            .envs(launch.env.iter().map(|(k, v)| (k.as_str(), v.as_str())))
            .env("HOME", &home)
            .env("PATH", "/usr/bin:/bin")
            .env("CHIMAERA_PRELUDE", &prelude)
            .output()
            .unwrap();
        let out = String::from_utf8_lossy(&out.stdout).into_owned();
        assert!(out.contains("RESULT:>rc>prelude"), "{out}");
        std::fs::remove_dir_all(&base).ok();
    }
