//! The wire-fixture bridge: Rust tests serialize the daemon↔UI shapes they
//! pin (chat `SeqEvent`s, the `/ws/chat`, `/ws/sessions` and `/ws/events`
//! frames, session rows) into checked-in JSON under
//! `web-ui/src/lib/net/fixtures/wire/`, and the web UI's Vitest consumer
//! tests (`web-ui/src/lib/net/wireFixtures.test.ts`) feed every fixture
//! through the real TypeScript decoders and reducers. The fixtures are the
//! executable form of "the daemon↔UI wire is a stable public interface"
//! (root `AGENTS.md`): a Rust change that moves a shape rewrites a fixture,
//! the diff shows up in review, and the UI tests say whether the client
//! still accepts it.
//!
//! Modes (`CHIMAERA_WIRE_FIXTURES`):
//! - `write` (the default outside CI): a plain `cargo test` regenerates the
//!   fixtures in place. Commit what changed; `just check` fails when the
//!   tree is dirty under the fixture dir after the tests ran.
//! - `check` (the default when `CI` is set): a fixture that differs from
//!   what the test produced — or is missing — fails the test, naming the
//!   file and the first differing line.
//!
//! Dev-dependency only: no daemon code paths run through here.

use serde_json::{json, Value};
use std::path::{Path, PathBuf};

/// Repository-relative directory the fixtures live in.
pub const FIXTURE_DIR: &str = "web-ui/src/lib/net/fixtures/wire";

const ENV_MODE: &str = "CHIMAERA_WIRE_FIXTURES";

/// One pinned frame: `name` is the stable key the consumer test addresses it
/// by, `note` says what the frame is (not how the client should treat it).
pub struct Case {
    pub name: &'static str,
    pub note: &'static str,
    pub frame: Value,
}

/// Build a [`Case`].
pub fn case(name: &'static str, note: &'static str, frame: Value) -> Case {
    Case { name, note, frame }
}

/// Write (or, in check mode, verify) the fixture file for one shape family.
///
/// `family` is the file stem (`chat-events`), `source` the Rust test that
/// pins it (`crates/chimaera-agent/src/model.rs`), `about` a sentence on what
/// the family covers. Keys serialize sorted (serde_json's default map), so
/// the document is byte-stable across runs; pretty-printed with a trailing
/// newline so diffs read per field.
pub fn pin(family: &str, source: &str, about: &str, cases: Vec<Case>) {
    assert!(
        family
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'),
        "fixture family names are kebab-case file stems, got {family:?}"
    );
    let mut seen = std::collections::BTreeSet::new();
    for case in &cases {
        assert!(
            seen.insert(case.name),
            "duplicate fixture case {:?} in {family}",
            case.name
        );
    }
    let document = json!({
        "$comment": format!(
            "Generated by `cargo test` ({source}); do not edit by hand. \
             The Rust test pins these shapes, the web-ui Vitest consumer \
             tests read them. Regenerate: run the Rust tests without \
             {ENV_MODE}=check, then commit the result."
        ),
        "family": family,
        "source": source,
        "about": about,
        "cases": cases
            .iter()
            .map(|c| json!({"name": c.name, "note": c.note, "frame": c.frame}))
            .collect::<Vec<_>>(),
    });
    let mut rendered = serde_json::to_string_pretty(&document).expect("fixture JSON");
    rendered.push('\n');

    let path = fixture_path(family);
    let on_disk = std::fs::read_to_string(&path).ok();
    if on_disk.as_deref() == Some(rendered.as_str()) {
        return;
    }
    match mode() {
        Mode::Check => panic!("{}", stale_message(&path, on_disk.as_deref(), &rendered)),
        Mode::Write => {
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent).expect("fixture dir");
            }
            std::fs::write(&path, rendered)
                .unwrap_or_else(|err| panic!("write {}: {err}", path.display()));
            eprintln!(
                "wire fixture {} {}; review and commit it",
                path.display(),
                if on_disk.is_some() {
                    "regenerated"
                } else {
                    "written"
                }
            );
        }
    }
}

enum Mode {
    Write,
    Check,
}

fn mode() -> Mode {
    match std::env::var(ENV_MODE).as_deref() {
        Ok("check") => Mode::Check,
        Ok("write") => Mode::Write,
        Ok(other) => panic!("{ENV_MODE} must be `write` or `check`, got {other:?}"),
        Err(_) => {
            if std::env::var("CI").is_ok_and(|v| !v.is_empty()) {
                Mode::Check
            } else {
                Mode::Write
            }
        }
    }
}

/// `<repo>/web-ui/src/lib/net/fixtures/wire/<family>.json`, resolved from
/// this crate's own manifest dir so every workspace crate lands in one place.
pub fn fixture_path(family: &str) -> PathBuf {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    // Canonical so a failure names the real file, not `crates/x/../../…`.
    let root = root.canonicalize().unwrap_or(root);
    root.join(FIXTURE_DIR).join(format!("{family}.json"))
}

fn stale_message(path: &Path, on_disk: Option<&str>, fresh: &str) -> String {
    let Some(on_disk) = on_disk else {
        return format!(
            "wire fixture {} is missing. Run the Rust tests without {ENV_MODE}=check \
             to write it, then commit it.",
            path.display()
        );
    };
    let first_diff = on_disk
        .lines()
        .zip(fresh.lines())
        .position(|(a, b)| a != b)
        .map(|i| {
            format!(
                "first difference at line {}:\n  committed: {}\n  fresh:     {}",
                i + 1,
                on_disk.lines().nth(i).unwrap_or(""),
                fresh.lines().nth(i).unwrap_or("")
            )
        })
        .unwrap_or_else(|| {
            format!(
                "the files differ in length ({} vs {} lines)",
                on_disk.lines().count(),
                fresh.lines().count()
            )
        });
    format!(
        "wire fixture {} is stale: the Rust shapes moved but the committed fixture did not. \
         {first_diff}\nRun the Rust tests without {ENV_MODE}=check to regenerate it, review the \
         diff (a shape change is a daemon↔UI contract change), run the web-ui tests, and commit.",
        path.display()
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fixture_path_lands_under_the_web_ui() {
        let path = fixture_path("x");
        assert!(path.ends_with("web-ui/src/lib/net/fixtures/wire/x.json"));
        assert!(path.join("../..").exists() || path.parent().is_some());
    }

    #[test]
    fn stale_message_names_the_first_differing_line() {
        let msg = stale_message(
            Path::new("f.json"),
            Some("{\n  \"a\": 1\n}\n"),
            "{\n  \"a\": 2\n}\n",
        );
        assert!(msg.contains("line 2"), "{msg}");
        assert!(msg.contains("\"a\": 1"), "{msg}");
        assert!(msg.contains("\"a\": 2"), "{msg}");
        let missing = stale_message(Path::new("f.json"), None, "{}");
        assert!(missing.contains("missing"), "{missing}");
    }
}
